function detectLocale(): AppLocale {
  const stored = window.localStorage.getItem(STORAGE_KEY) as AppLocale | null;
  if (stored && supportedLocales.has(stored)) {
    return stored;
  }
  const browserLocale = navigator.language.toLowerCase();
  if (browserLocale.startsWith("th")) {
    return "th-TH";
  }
  if (browserLocale.startsWith("en")) {
    return "en-US";
  }
  return DEFAULT_LOCALE;
}

export const currentLocale = ref<AppLocale>(detectLocale());

export function setLocale(locale: AppLocale) {
  if (!supportedLocales.has(locale)) {
    currentLocale.value = DEFAULT_LOCALE;
    return;
  }
  currentLocale.value = locale;
}

export function t(key: string, vars: Record<string, string | number | null | undefined> = {}) {
  const template = messages[currentLocale.value][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => String(vars[name] ?? ""));
}

export function useI18n() {
  const currentLanguageLabel = computed(() => languageOptions.find((item) => item.value === currentLocale.value)?.nativeLabel || "中文");
  return {
    locale: currentLocale,
    languageOptions,
    currentLanguageLabel,
    setLocale,
    t
  };
}

watch(
  currentLocale,
  (locale) => {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  },
  { immediate: true }
);
